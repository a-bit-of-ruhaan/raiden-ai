// Setup Marked Markdown parser
function initMarkdownParser() {
  if (typeof marked !== 'undefined') {
    const renderer = new marked.Renderer();

    // Custom code block renderer with copy button & language badge
    renderer.code = function(arg1, arg2) {
      const rawCode = (typeof arg1 === 'object' && arg1 !== null) ? (arg1.text || '') : (arg1 || '');
      const language = (typeof arg1 === 'object' && arg1 !== null) ? (arg1.lang || 'plaintext') : (arg2 || 'plaintext');
      let highlighted = rawCode;
      if (typeof hljs !== 'undefined') {
        try {
          if (hljs.getLanguage(language)) {
            highlighted = hljs.highlight(rawCode, { language }).value;
          } else {
            highlighted = hljs.highlightAuto(rawCode).value;
          }
        } catch (e) {
          highlighted = rawCode;
        }
      }

      return `
        <div class="code-block-wrapper">
          <div class="code-block-header">
            <span class="code-lang-tag">${language}</span>
            <button class="btn-copy-code" onclick="copyCodeBlock(this)">
              ${ICONS.copy}
              <span>Copy</span>
            </button>
          </div>
          <pre><code class="hljs language-${language}">${highlighted}</code></pre>
        </div>
      `;
    };

    if (typeof marked.use === 'function') {
      marked.use({ renderer });
    }
    if (typeof marked.setOptions === 'function') {
      marked.setOptions({
        renderer: renderer,
        breaks: true,
        gfm: true
      });
    }
  }
}

function renderMarkdown(text) {
  if (!text) return '';
  if (typeof marked !== 'undefined') {
    try {
      return marked.parse(text);
    } catch (e) {
      console.warn('Markdown parsing error:', e);
      return escapeHtml(text).replace(/\n/g, '<br>');
    }
  }
  return escapeHtml(text).replace(/\n/g, '<br>');
}

function escapeHtml(string) {
  const map = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#039;'
  };
  return String(string).replace(/[&<>"']/g, function(m) { return map[m]; });
}

function copyCodeBlock(button, fallbackText) {
  let text = fallbackText;
  if (!text) {
    const wrapper = button.closest('.code-block-wrapper');
    const codeEl = wrapper ? wrapper.querySelector('pre code') : null;
    text = codeEl ? codeEl.innerText : '';
  }
  navigator.clipboard.writeText(text).then(() => {
    const originalHtml = button.innerHTML;
    button.innerHTML = `${ICONS.check} <span>Copied!</span>`;
    setTimeout(() => {
      button.innerHTML = originalHtml;
    }, 1800);
  }).catch(() => {
    showToast('Failed to copy code', 'error');
  });
}

function copyToClipboard(text, successMsg = 'Copied to clipboard') {
  navigator.clipboard.writeText(text).then(() => {
    showToast(successMsg, 'success');
  }).catch(() => {
    showToast('Failed to copy', 'error');
  });
}

// Modern Toast Notifications with Smooth Entry/Exit
function showToast(message, type = 'info') {
  const container = document.getElementById('toast-container');
  if (!container) return;

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  let icon = ICONS.lightning;
  if (type === 'success') icon = ICONS.check;
  if (type === 'error') icon = ICONS.close;
  if (type === 'warning') icon = ICONS.sparkle;

  toast.innerHTML = `<span style="display: flex; align-items: center; color: var(--accent-cyan); width: 16px; height: 16px;">${icon}</span><span>${escapeHtml(message)}</span>`;
  container.appendChild(toast);

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateY(-10px)';
    toast.style.transition = 'all 0.25s cubic-bezier(0.16, 1, 0.3, 1)';
    setTimeout(() => toast.remove(), 250);
  }, 2800);
}

// Relative Time Helper
function timeAgo(dateString) {
  const date = new Date(dateString);
  const now = new Date();
  const diffSec = Math.floor((now - date) / 1000);

  if (diffSec < 60) return 'Just now';
  if (diffSec < 3600) return `${Math.floor(diffSec / 60)}m ago`;
  if (diffSec < 86400) return `${Math.floor(diffSec / 3600)}h ago`;
  if (diffSec < 604800) return `${Math.floor(diffSec / 86400)}d ago`;
  return date.toLocaleDateString();
}

function formatBytes(bytes, decimals = 1) {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

// Modal helpers
function openModal(id) {
  const modal = document.getElementById(id);
  if (modal) {
    modal.classList.add('open');
    modal.classList.add('active');
  }
}

function closeModal(id) {
  const modal = document.getElementById(id);
  if (modal) {
    modal.classList.remove('open');
    modal.classList.remove('active');
  }
}

